/* Test cases: 100 varied cases for the workflow. Browse, load into the form or the assistant, run one or all, and see pass/fail
   against the expected outcome. Expectations come from testcases.js (generated by benchmark/generate_frontend_cases.py). */
import { $, $$, esc, api, busy, modelQS, state, announce, noteRun } from "./core.js";
import { icon, panel, pill, statusPill, statTile, runCountUps, originTag, dataTable, emptyState } from "./ui.js";
import { N, LABELS } from "./fmt.js";
import { registerView, show } from "./chrome.js";
import { render as renderDesign, designForm, fillForm } from "./design.js";
import { CASES } from "./testcases.js";

const host = $("#view-tests");
const results = new Map();           // id -> { state: "pass"|"fail"|"skip"|"error", checks: [{label, ok, detail}], res, error }
let table = null, running = false, cancel = false;

const CATS = [...new Set(CASES.map((c) => c.cat))];
const STATUSES = [...new Set(CASES.map((c) => c.expect.status))];
const FORM_UNITS = { span: "m", b: "mm", D: "mm", cover: "mm", dead_load: "kN/m", live_load: "kN/m" };
const FIELD_NAMES = { span: "Span", support: "Support", b: "Width b", D: "Depth D", cover: "Cover", fck: "Concrete", fy: "Steel", dead_load: "Dead load", live_load: "Live load", exposure: "Exposure" };

/* ---------------------------------------------------------------- helpers */
const keyReady = () => !!state.health?.llm_configured;
const skippable = (c) => c.llm && !keyReady();

function describe(c) {
  if (c.path === "chat") return c.input.brief;
  const i = c.input, q = (k) => (i[k] ? `${i[k].value} ${i[k].unit ?? "(no unit)"}` : "—");
  return `${i.support ?? "—"}, span ${q("span")}, ${q("b")} × ${q("D")}, cover ${q("cover")}, fck ${i.fck ?? "—"}, fy ${i.fy ?? "—"}, DL ${q("dead_load")}, LL ${q("live_load")}, ${i.exposure ?? "—"}`;
}

/* a form case can be typed into the Form design page only if every field is present, in the form's own units and select values */
function formValues(c) {
  if (c.path !== "form") return null;
  const i = c.input;
  for (const k of Object.keys(FIELD_NAMES)) if (i[k] === undefined) return null;
  for (const [k, u] of Object.entries(FORM_UNITS)) if (i[k].unit !== u) return null;
  if (!["simply_supported", "cantilever"].includes(i.support)) return null;
  if (![20, 25, 30, 35, 40].includes(+i.fck) || ![250, 415, 500].includes(+i.fy)) return null;
  if (!["mild", "moderate", "severe", "very severe", "very_severe", "extreme"].includes(i.exposure)) return null;
  return { support: i.support, span_m: i.span.value, b_mm: i.b.value, D_mm: i.D.value, cover_mm: i.cover.value, exposure: i.exposure.replace(" ", "_"),
    fck: i.fck, fy: i.fy, dead_load_kN_per_m: i.dead_load.value, live_load_kN_per_m: i.live_load.value };
}

/* ---------------------------------------------------------------- evaluation: mirrors benchmark/verify_frontend_cases.py */
function evaluate(c, res) {
  const e = c.expect, out = [];
  const add = (label, ok, detail = "") => out.push({ label, ok, detail });
  add(`Status is "${LABELS[e.status] || e.status}"`, res.status === e.status, `got "${LABELS[res.status] || res.status}"${res.message ? ": " + res.message.slice(0, 140) : ""}`);
  if (e.enlarged) { const a = res.original_input, b = res.final_input; add("Section was enlarged by the reviser", !!(a && b && (a.b_mm !== b.b_mm || a.D_mm !== b.D_mm)), b ? `${b.b_mm} × ${b.D_mm} mm` : "no design"); }
  if (e.conversions) add("Unit conversions recorded", (res.conversions || []).length > 0, (res.conversions || []).join("; "));
  const failed = (res.checks || []).filter((k) => !k.passed && k.severity === "error").map((k) => k.rule_id);
  const warned = (res.checks || []).filter((k) => !k.passed && k.severity === "warning").map((k) => k.rule_id);
  for (const r of e.failed || []) add(`Rule ${r} fails`, failed.includes(r), `failed: ${failed.join(", ") || "none"}`);
  for (const r of e.warn || []) add(`Rule ${r} warns`, warned.includes(r), `warnings: ${warned.join(", ") || "none"}`);
  for (const m of e.missing || []) add(`"${FIELD_NAMES[m] || m}" reported missing`, (res.missing || []).includes(m), `missing: ${(res.missing || []).join(", ") || "none"}`);
  for (const k of ["fck", "fy"]) if (e[k] !== undefined) add(`${k} stays ${e[k]}`, res.final_input?.[k] === e[k], `got ${res.final_input?.[k] ?? "no design"}`);
  for (const t of e.events || []) add(`Guardrail event "${t}" logged`, (res.guardrail_events || []).some((g) => g.type === t), `events: ${(res.guardrail_events || []).map((g) => g.type).join(", ") || "none"}`);
  return out;
}

/* ---------------------------------------------------------------- running */
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function call(c) {
  const body = c.path === "form" ? c.input
    : { messages: [{ role: "user", text: c.input.brief }], attachment_text: c.input.attachment || "", images: [] };
  return api((c.path === "form" ? "/api/design" : "/api/chat") + modelQS(), { method: "POST", body });
}
async function runOne(c, onWait) {
  for (let tries = 0; ; tries++) {
    try {
      const res = await call(c);
      noteRun(res);
      const checks = evaluate(c, res);
      results.set(c.id, { state: checks.every((k) => k.ok) ? "pass" : "fail", checks, res });
      return;
    } catch (err) {
      const wait = /retry in (\d+)s/.exec(err.message);
      if (wait && tries < 3) { onWait?.(+wait[1] + 1); await sleep((+wait[1] + 1) * 1000); continue; }
      results.set(c.id, { state: "error", checks: [], error: err.message });
      return;
    }
  }
}

async function runAll(list) {
  if (running) return;
  running = true; cancel = false;
  const todo = list.filter((c) => !skippable(c));
  for (const c of list) if (skippable(c)) results.set(c.id, { state: "skip", checks: [], error: "Needs GEMINI_API_KEY" });
  const btn = $("#tc-run-all"), stop = $("#tc-stop");
  busy(btn, true, "Run all shown"); stop.hidden = false;
  let n = 0;
  for (const c of todo) {
    if (cancel) break;
    $("#tc-progress").textContent = `Running ${++n} of ${todo.length}: ${c.id} ${c.title}`;
    await runOne(c, (s) => { $("#tc-progress").textContent = `Rate limit reached, waiting ${s}s, then continuing (${n} of ${todo.length})`; });
    drawSummary(); table.redraw();
  }
  $("#tc-progress").textContent = cancel ? `Stopped after ${n - 1} of ${todo.length}.` : `Finished ${todo.length} case${todo.length === 1 ? "" : "s"}.`;
  running = false; stop.hidden = true; busy(btn, false, "Run all shown");
  const s = tally(); announce(`Test run finished: ${s.pass} passed, ${s.fail + s.error} failed`);
}

/* ---------------------------------------------------------------- loading a case into the real pages */
function load(c) {
  if (c.path === "chat") {
    show("chat");
    $("#btn-reset")?.click();
    const b = $("#brief"); b.value = c.input.brief; b.dispatchEvent(new Event("input")); $("#attachment").value = c.input.attachment || "";
    if (c.input.attachment) $("#attachment").closest("details").open = true;
    b.focus();
  } else {
    const v = formValues(c); if (!v) return;
    show("design"); fillForm(designForm(), v); designForm().dispatchEvent(new Event("input"));
  }
  announce(`Loaded ${c.id}: ${c.title}`);
}

/* ---------------------------------------------------------------- view */
const tally = (list = CASES) => {
  const t = { pass: 0, fail: 0, error: 0, skip: 0, notrun: 0 };
  for (const c of list) t[results.get(c.id)?.state || "notrun"]++;
  return t;
};
function resultPill(c) {
  const r = results.get(c.id);
  if (!r) return '<span class="mut">not run</span>';
  return { pass: pill("pass", "Pass"), fail: pill("fail", "Fail"), error: pill("fail", "Error"), skip: pill("neutral", "Skipped") }[r.state];
}
function drawSummary() {
  const t = tally(), ran = t.pass + t.fail + t.error;
  $("#tc-tiles").innerHTML = statTile({ value: CASES.length, label: "cases" }) + statTile({ value: CASES.filter((c) => c.path === "form").length, label: "form" })
    + statTile({ value: CASES.filter((c) => c.path === "chat").length, label: "assistant", sub: `${CASES.filter((c) => c.llm).length} need a key` })
    + statTile({ value: ran, label: "run so far" }) + statTile({ value: t.pass, label: "passed" }) + statTile({ value: t.fail + t.error, label: "failed" });
  runCountUps($("#tc-tiles"));
}

function filtered() {
  const f = new FormData($("#tc-filters")), q = String(f.get("q") || "").trim().toLowerCase();
  return CASES.filter((c) => (!f.get("cat") || c.cat === f.get("cat")) && (!f.get("path") || c.path === f.get("path"))
    && (!f.get("status") || c.expect.status === f.get("status"))
    && (!f.get("key") || (f.get("key") === "yes") === !!c.llm)
    && (!f.get("result") || (f.get("result") === "notrun" ? !results.has(c.id) : results.get(c.id)?.state === f.get("result")))
    && (!q || `${c.id} ${c.title} ${c.cat} ${c.note} ${describe(c)}`.toLowerCase().includes(q)));
}

function detail(c) {
  const r = results.get(c.id), fv = formValues(c);
  const inputBlock = c.path === "chat"
    ? `<dt>Brief</dt><dd>${esc(c.input.brief)}</dd>${c.input.attachment ? `<dt>Attachment</dt><dd>${esc(c.input.attachment)}</dd>` : ""}`
    : `<dt>Input sent</dt><dd><pre class="tc-json">${esc(JSON.stringify(c.input, null, 1))}</pre></dd>`;
  const exp = Object.entries(c.expect).map(([k, v]) => `<li><b>${esc(k)}</b> ${esc(Array.isArray(v) ? v.join(", ") : String(v))}</li>`).join("");
  let outcome = "";
  if (r?.state === "skip") outcome = `<p class="warnline">${esc(r.error)}. Set a key in backend/.env to run this case, or use Load and try it by hand.</p>`;
  else if (r?.state === "error") outcome = `<p class="warnline">The request failed: ${esc(r.error)}</p>`;
  else if (r) outcome = `<ul class="tc-checks">${r.checks.map((k) => `<li class="${k.ok ? "ok" : "bad"}">${icon(k.ok ? "pass" : "fail")}<span>${esc(k.label)}${k.ok ? "" : ` <small>${esc(k.detail)}</small>`}</span></li>`).join("")}</ul>`;
  return `<div class="xbox"><dl class="kv wide"><dt>Tests</dt><dd>${esc(c.note)}</dd>${inputBlock}<dt>Expected</dt><dd><ul class="tc-exp">${exp}</ul></dd></dl>${outcome}
    <div class="actions"><button class="btn ghost sm" data-load="${esc(c.id)}" type="button" ${c.path === "form" && !fv ? 'disabled title="This input cannot be typed into the form (other units, missing or invalid values). Use Run."' : ""}>${icon("form")} Load into ${c.path === "form" ? "Form design" : "Assistant"}</button>
    <button class="btn ghost sm" data-run="${esc(c.id)}" type="button" ${running ? "disabled" : ""}>${icon("play")} Run this case</button>
    ${r?.res?.design ? `<button class="btn ghost sm" data-open="${esc(c.id)}" type="button">Open the full result</button>` : ""}</div></div>`;
}

function drawTable() {
  const rows = filtered();
  $("#tc-count").textContent = `${rows.length} of ${CASES.length} shown`;
  const cols = [
    { key: "id", label: "ID", cls: "clause nowrap" },
    { key: "cat", label: "Category", cls: "nowrap" },
    { key: "title", label: "Case", cls: "wrapok", render: (c) => `<b>${esc(c.title)}</b>` },
    { key: "path", label: "Via", cls: "nowrap", render: (c) => `${c.path === "form" ? "Form" : "Assistant"}${c.llm ? " " + originTag("llm") : ""}` },
    { key: "exp", label: "Expected", cls: "nowrap", sortVal: (c) => c.expect.status, render: (c) => statusPill(c.expect.status) },
    { key: "res", label: "Result", cls: "nowrap", sortVal: (c) => results.get(c.id)?.state || "zz", render: resultPill },
    { key: "act", label: "", sort: false, cls: "nowrap", render: (c) => `<button class="btn ghost sm" data-run="${esc(c.id)}" type="button" aria-label="Run ${esc(c.id)}" ${running ? "disabled" : ""}>${icon("play")} Run</button>` },
  ];
  const cfg = { rows, cols, id: "tc-tbl", empty: emptyState({ title: "No cases match", text: "Change or clear the filters." }), expand: detail,
    after: (h) => {
      $$("[data-run]", h).forEach((b) => { b.onclick = async (e) => { e.stopPropagation(); const c = CASES.find((x) => x.id === b.dataset.run); if (skippable(c)) { results.set(c.id, { state: "skip", checks: [], error: "Needs GEMINI_API_KEY" }); } else { busy(b, true); await runOne(c); } drawSummary(); table.redraw(); }; });
      $$("[data-load]", h).forEach((b) => { b.onclick = () => load(CASES.find((x) => x.id === b.dataset.load)); });
      $$("[data-open]", h).forEach((b) => { b.onclick = async () => { show("design"); await renderDesign(results.get(b.dataset.open).res); }; });
    } };
  if (table) table.setRows(rows); else table = dataTable($("#tc-table"), cfg);
}

