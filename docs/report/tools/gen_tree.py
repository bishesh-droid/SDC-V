"""Generate sections/appendix_b_tree.tex: the project directory tree, read from the repository."""
from __future__ import annotations

import os
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
ROOT = HERE.parent.parent
SKIP_DIRS = {".git", "__pycache__", ".pytest_cache", ".claude-flow", ".impeccable", ".venv", "node_modules", ".swarm", ".claude"}
SKIP_FILES = {".env", "audit.db"}                      # secrets and the live database are never listed
SKIP_SUFFIX = {".zip", ".pyc"}
COLLAPSE = {"outputs": "trained adapters and model outputs (not listed)", "data": None}
NOTE = {"docs": None}


def entries(p: Path):
    items = [e for e in p.iterdir()
             if e.name not in SKIP_DIRS and e.name not in SKIP_FILES and e.suffix not in SKIP_SUFFIX]
    return sorted(items, key=lambda e: (e.is_file(), e.name.lower()))


def walk(p: Path, prefix: str, out: list[str], depth: int):
    es = entries(p)
    for i, e in enumerate(es):
        last = i == len(es) - 1
        out.append(f"{prefix}{'\\-- ' if last else '|-- '}{e.name}{'/' if e.is_dir() else ''}")
        if e.is_dir():
            if p.name == "training" and e.name == "outputs":
                out.append(f"{prefix}{'    ' if last else '|   '}`-- (trained adapters and outputs, not listed)")
                continue
            walk(e, prefix + ("    " if last else "|   "), out, depth + 1)


def main():
    lines = ["SDC-V/"]
    walk(ROOT, "", lines, 0)
    body = "\n".join(lines)
    tex = ("% Generated by tools/gen_tree.py. Do not edit by hand.\n"
           "\\chapter{Project directory tree}\\label{app:tree}\n\n"
           "The tree below was read from the repository when this report was built. Caches, tooling state "
           "(\\code{.claude-flow}, \\code{.pytest_cache}, \\code{__pycache__}), archives, the live database file, "
           "environment files and the trained model outputs are omitted.\n\n"
           "\\begin{lstlisting}[basicstyle=\\ttfamily\\scriptsize,breaklines=false]\n" + body + "\n\\end{lstlisting}\n")
    (HERE / "sections" / "appendix_b_tree.tex").write_text(tex, encoding="utf-8")
    print(len(lines), "lines")


if __name__ == "__main__":
    main()
